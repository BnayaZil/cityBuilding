import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const testCasesPath = path.join(root, "TEST_CASES.md");

const suiteFiles = [
  "crates/scanner-core/tests/test_cases.rs",
  "crates/cli/tests/test_cases.rs",
  "packages/github-action/tests/test-cases.spec.ts",
  "packages/world-server/tests/test-cases.spec.ts",
  "packages/renderer/tests/test-cases.spec.ts",
  "packages/web/tests/test-cases.spec.ts",
];

const caseDoc = await readFile(testCasesPath, "utf8");
const docIds = [...caseDoc.matchAll(/\|\s(\d+\.\d+\.\d+[a-z]?)\s\|/g)].map((m) => m[1]);

const idToSuite = new Map();
for (const file of suiteFiles) {
  const abs = path.join(root, file);
  const content = await readFile(abs, "utf8");
  const ids = [...content.matchAll(/"(\d+\.\d+\.\d+[a-z]?)"/g)].map((m) => m[1]);
  for (const id of ids) {
    if (!idToSuite.has(id)) {
      idToSuite.set(id, new Set());
    }
    idToSuite.get(id).add(file);
  }
}

const missing = docIds.filter((id) => !idToSuite.has(id));
if (missing.length > 0) {
  throw new Error(`Unmapped TEST_CASES IDs: ${missing.join(", ")}`);
}

const rows = docIds.map((id) => `| ${id} | ${[...idToSuite.get(id)].join(", ")} |`);
const output = [
  "# Test Case Index",
  "",
  "Generated by `scripts/generate-test-case-index.mjs`.",
  "",
  "| Case ID | Executable Test File(s) |",
  "|---|---|",
  ...rows,
  "",
].join("\n");

await writeFile(path.join(root, "TEST_CASE_INDEX.md"), output, "utf8");
console.log(`Generated TEST_CASE_INDEX.md with ${docIds.length} mapped cases.`);
